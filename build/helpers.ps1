# Compiles omawin.exe and the bar's helpers with the C# compiler that ships with Windows
# (C# 5), into $OutDir. The one place these command lines live: install.ps1's helpers step runs
# it on this PC, and CI (.github/workflows/release.yml) runs it to build the release's
# omawin-helpers ZIP, so a local build and a release are the same build.
#
#   .\build\helpers.ps1                              into ~/.local/bin
#   .\build\helpers.ps1 -OutDir ..\scratch\bin
#   .\build\helpers.ps1 -OutDir ..\scratch\bin -Release v0.1.0   (omawin --version says so)
#
# Safe to run again: an exe newer than its source is left alone. A running helper (the bar's voice-meter) locks
# its exe, but a running exe can still be renamed: the old one is moved aside and the running copy
# goes on until it is restarted.
param(
    [string]$OutDir = "$HOME\.local\bin",
    # The release the build is from, for `omawin --version`. CI passes the tag; without it the exe
    # says (dev), which is how a download is told from a build off a checkout.
    [string]$Release
)
$ErrorActionPreference = 'Stop'

# install.ps1's step output, when this runs inside an install (install/lib.ps1 dot-sources them);
# plain output on its own (CI).
if (-not (Get-Command Write-Note -ErrorAction SilentlyContinue)) {
    function Write-Note([string]$Text) { Write-Host "    $Text" -ForegroundColor DarkGray }
    function Write-Warn([string]$Text) { Write-Host "    ! $Text" -ForegroundColor Yellow }
}

$Repo = Split-Path $PSScriptRoot
if (-not [IO.Path]::IsPathRooted($OutDir)) { $OutDir = Join-Path (Get-Location).Path $OutDir }
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$csc = Get-ChildItem "$env:WINDIR\Microsoft.NET\Framework64\v4*\csc.exe" -ErrorAction SilentlyContinue | Select-Object -Last 1
if (-not $csc) { throw 'the C# compiler (csc.exe) is not on this PC; it ships with Windows/.NET Framework' }

# omawin: the setup's commands (bin/commands.txt; the keys run it). voice-meter: the bar's
# voice typing (Win+H) equalizer.
$helpers = @(
    @{ Name = 'omawin'; Source = "$Repo\bin\omawin.cs"; Target = 'exe' }
    @{ Name = 'voice-meter'; Source = "$Repo\bin\voice-meter.cs"; Target = 'exe' }
    # omawin-listen: Ctrl+Win+H, records what you say for omawin's agent (src/agent/).
    @{ Name = 'omawin-listen'; Source = "$Repo\src\agent\omawin-listen.cs"; Target = 'winexe' }
)

# The release stamp. Two things: a generated file with the assembly attributes every helper carries
# (so `(Get-Item omawin.exe).VersionInfo.ProductVersion` says which release it is, like the menu app
# and the player), and the constant omawin.cs picks up under /define:OMAWIN_VERSION (bin/omawin.cs:
# `omawin --version`).
$stamp = $null
if ($Release) {
    # AssemblyFileVersion needs numbers: v0.1.0 -> 0.1.0.0; anything else (v0.0.0-dev) -> 0.0.0.0.
    $numeric = ($Release -replace '^v', '') -replace '[^0-9.].*$', ''
    if ($numeric -notmatch '^\d+(\.\d+){1,3}$') { $numeric = '0.0.0.0' }
    while ($numeric.Split('.').Count -lt 4) { $numeric += '.0' }
    $stamp = Join-Path ([IO.Path]::GetTempPath()) "omawin-buildinfo-$PID.cs"
    Set-Content -Path $stamp -Encoding UTF8 -Value @"
// Generated by build/helpers.ps1: the release these exes are from.
[assembly: System.Reflection.AssemblyInformationalVersion("$Release")]
[assembly: System.Reflection.AssemblyFileVersion("$numeric")]
[assembly: System.Reflection.AssemblyVersion("$numeric")]
static class BuildInfo { public const string Version = "$Release"; }
"@
}

try {
    foreach ($h in $helpers) {
        $out = Join-Path $OutDir "$($h.Name).exe"
        $exe = Get-Item $out -ErrorAction SilentlyContinue
        if ($exe -and $exe.LastWriteTime -ge (Get-Item $h.Source).LastWriteTime) { Write-Note "ok  $($h.Name).exe"; continue }
        # A running helper (the bar's voice-meter) locks its exe: move it aside so the new one can be written.
        if ($exe) {
            Remove-Item "$out.old" -Force -ErrorAction SilentlyContinue
            try { Move-Item $out "$out.old" -ErrorAction Stop } catch { }
        }
        $references = @($h.References | Where-Object { $_ })
        $define = @()
        $sources = @($h.Source)
        if ($stamp) { $sources += $stamp }
        if ($h.Name -eq 'omawin' -and $stamp) { $define = @('/define:OMAWIN_VERSION') }
        & $csc.FullName /nologo "/target:$($h.Target)" /optimize @references @define "/out:$out" @sources
        if ($LASTEXITCODE -eq 0) { Write-Note "built $out" }
        else {
            # Keep the old one rather than leave nothing, then fail (install.ps1 warns and carries
            # on; CI fails the build).
            if (-not (Test-Path $out) -and (Test-Path "$out.old")) { Move-Item "$out.old" $out }
            throw "$($h.Name) build failed (see above)"
        }
    }
} finally {
    if ($stamp) { Remove-Item $stamp -Force -ErrorAction SilentlyContinue }
}
